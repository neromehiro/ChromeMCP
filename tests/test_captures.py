    def test_png_is_saved_without_image_tool_output(self):
        # A complete 1x1 PNG fixture, independent of untracked live screenshots.
        original = base64.b64decode(
            "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+ip1sAAAAASUVORK5CYII="
        )
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "capture.png"
            result = save_capture(base64.b64encode(original).decode(), 17, str(path))
            self.assertEqual(result["format"], "png")
            self.assertEqual((result["width"], result["height"]), (1, 1))
            self.assertEqual(result["path"], str(path))
            self.assertEqual(path.read_bytes(), original)


